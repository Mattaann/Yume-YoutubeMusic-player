const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const folder = path.join(__dirname,'..','WebView','Scripts');
let messages = [], clicks = 0, handlers = {};
let shuffleCalls = 0, repeatCalls = 0;
const media = {duration:180,currentTime:25,volume:0.7,muted:false,paused:false,ended:false,readyState:4,seekable:{length:1,start:()=>0,end:()=>180},addEventListener(){},removeEventListener(){}};
const bar={repeatMode:'NONE',hasAttribute:()=>shuffleCalls>0,queue:{shuffle(){shuffleCalls++;}},onRepeatButtonClick(){repeatCalls++;this.repeatMode=['NONE','ALL','ONE'][repeatCalls%3];}};
const nodes = {'video, audio':media,'ytmusic-player-bar #play-pause-button':{click(){clicks++;}},'ytmusic-player-bar':bar};
const context = {console,performance:{now:()=>1000},queueMicrotask,MutationObserver:class{observe(){}disconnect(){}},navigator:{mediaSession:{metadata:{title:'Test track',artist:'Test artist',album:'Test album',artwork:[]}}},document:{body:{},querySelector:s=>nodes[s],addEventListener:(name,f)=>handlers[name]=f},window:{chrome:{webview:{postMessage:m=>messages.push(m)}}}};
vm.createContext(context);
vm.runInContext(['selectors','metadata','controls','navigation','context','observer','bridge'].map(n=>fs.readFileSync(path.join(folder,n+'.js'),'utf8')).join('\n'),context);
const command=context.window.__nocturne.command;
assert.equal(messages.at(-1).data.title,'Test track');
command({command:'volume',value:7}); assert.equal(media.volume,1);
command({command:'seek',value:-5}); assert.equal(media.currentTime,0);
command({command:'seek',value:999}); assert.equal(media.currentTime,180);
command({command:'seek',value:NaN}); assert.equal(media.currentTime,180);
nodes['.html5-video-player.ad-showing, .html5-video-player.ad-interrupting']={};
command({command:'seek',value:10}); assert.equal(media.currentTime,180);
assert.equal(messages.at(-1).data.canSeek,false);
delete nodes['.html5-video-player.ad-showing, .html5-video-player.ad-interrupting'];
command({command:'shuffle'});assert.equal(shuffleCalls,1);assert.equal(messages.at(-1).data.shuffleActive,true);
command({command:'repeat'});assert.equal(repeatCalls,1);assert.equal(messages.at(-1).data.repeatMode,1);
command({command:'repeat'});assert.equal(messages.at(-1).data.repeatMode,2);
command({command:'repeat'});assert.equal(messages.at(-1).data.repeatMode,0);
command({command:'mute'}); assert.equal(media.muted,true);
command({command:'toggle'}); assert.equal(clicks,1);
handlers.keydown({composedPath:()=>[{tagName:'INPUT'}],code:'Space'}); assert.equal(clicks,1);
handlers.keydown({composedPath:()=>[],code:'Space',preventDefault(){},stopImmediatePropagation(){}}); assert.equal(clicks,2);
console.log('PASS: metadata, bounded commands, mute, playback and editable-field shortcut protection');
